export type Delivery = NonNullable<ProjectState['delivery']>;

/** owner/name from GitHub-style remote URLs (https, ssh, scp-like). */
export function parseGitHubRemote(url: string): { host: string; repository: string } | undefined {
  const m = /^(?:https?:\/\/(?:[^@/]+@)?|ssh:\/\/(?:[^@/]+@)?|[^@/]+@)([^/:]+)[:/]([\w.-]+\/[\w.-]+?)(?:\.git)?\/?$/.exec(url.trim());
  return m ? { host: m[1], repository: m[2] } : undefined;
}

export function pullRequestBody(state: ProjectState, backlog: Backlog): string {
  const trace = traceability(backlog, state);
  const cost = state.invocations.reduce((s, i) => s + (i.costUsd ?? 0), 0);
  const answered = backlog.openQuestions.filter(q => q.answer?.trim());
  const cell = (t: string) => t.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  return [
    `> Generated by Agent Orchestrator from **${state.document.name}**. Every task passed the configured checks and an independent AI review; **a human review is still required before merging.**`,
    '', '## Summary', '', backlog.summary, '',
    '## Tasks', '', '| Task | Commit | Attempts | Reviewer |', '|---|---|---|---|',
    ...taskOrder(backlog.tasks).map(t => {
      const s = state.tasks[t.id];
      return `| ${t.id}: ${cell(t.title)} | ${s?.commit ? `\`${s.commit.slice(0, 10)}\`` : s?.status ?? '-'} | ${s?.attempts ?? 0} | ${cell((s?.reviewSummary ?? '').slice(0, 200))} |`;
    }),
    '', '## Requirement coverage', '', '| Requirement | Priority | Status | Tasks |', '|---|---|---|---|',
    ...trace.map(r => `| ${r.id}: ${cell(r.title)} | ${r.priority} | ${r.status} | ${r.tasks.map(t => t.id).join(', ') || '-'} |`),
    ...(answered.length ? ['', '## Product-owner clarifications', '', ...answered.map(q => `- **${q.id}** ${q.question} → ${q.answer}`)] : []),
    ...(backlog.outOfScope.length ? ['', '## Out of scope', '', ...backlog.outOfScope.map(o => `- ${o}`)] : []),
    '', '## Verification', '',
    `- Integration checks on this branch: ${state.integration ? (state.integration.passed ? 'passed' : '**failed**') : 'not run'}`,
    `- Agent spend: $${cost.toFixed(2)} · prompt version \`${state.promptVersion}\` · project \`${state.id}\``,
  ].join('\n');
}

class GitHub {
  constructor(private apiUrl: string, private token: string, private doFetch: typeof fetch) {}
  async call<T>(method: string, path: string, body?: unknown): Promise<T> {
    const res = await this.doFetch(`${this.apiUrl.replace(/\/$/, '')}${path}`, {
      method, body: body === undefined ? undefined : JSON.stringify(body),
      headers: { authorization: `Bearer ${this.token}`, accept: 'application/vnd.github+json', 'x-github-api-version': '2022-11-28', 'content-type': 'application/json', 'user-agent': 'agent-orchestrator' },
    });
    if (!res.ok) throw new Error(`GitHub ${method} ${path} failed: ${res.status} ${(await res.text()).slice(0, 300)}`);
    return await res.json() as T;
  }
}

export interface DeliverOptions { fetch?: typeof fetch; /** Deliver a partial project too (default: completed only). */ allowPartial?: boolean; }

/** Pushes the project branch and opens (or updates) a draft PR, as configured. Idempotent. */
export async function deliverProject(dir: string, store: ProjectStore, opts: DeliverOptions = {}): Promise<Delivery | undefined> {
  const { state, backlog, config } = await readProject(dir);
  const d = config.delivery;
  if (!d.push) return undefined;
  if (state.status !== 'completed' && !(opts.allowPartial && state.status === 'partial')) throw new Error(`Project is ${state.status}; only completed projects are delivered`);
  const delivery: Delivery = { ...state.delivery };
  delete delivery.error;
  const record = async (type: string, data: Record<string, unknown>) => {
    state.delivery = delivery;
    state.updatedAt = new Date().toISOString();
    await store.saveState(dir, state);
    await store.appendEvent(dir, { projectId: state.id, type, data, at: state.updatedAt });
  };
  try {
    const remoteUrl = (await git(['remote', 'get-url', d.remote], state.repo)).stdout.trim();
    const token = process.env[d.pullRequest.tokenEnv];
    await git(['push', '--quiet', d.remote, `${state.branch}:refs/heads/${state.branch}`], state.worktree, pushAuth(remoteUrl, token));
    Object.assign(delivery, { pushedAt: new Date().toISOString(), remote: d.remote });
    if (d.pullRequest.enabled) {
      if (!token) throw new Error(`Opening a pull request needs a token in $${d.pullRequest.tokenEnv}`);
      const repository = d.pullRequest.repository ?? parseGitHubRemote(remoteUrl)?.repository;
      if (!repository) throw new Error(`Cannot tell the GitHub repository from remote ${d.remote}; set delivery.pullRequest.repository`);
      const pr = await openOrUpdatePullRequest(new GitHub(d.pullRequest.apiUrl, token, opts.fetch ?? fetch), repository, state, backlog!, d.pullRequest);
      Object.assign(delivery, { prUrl: pr.html_url, prNumber: pr.number });
    }
    await record('delivery.finished', { remote: d.remote, branch: state.branch, prUrl: delivery.prUrl });
    return delivery;
  } catch (error) {
    delivery.error = error instanceof Error ? error.message : String(error);
    await record('delivery.failed', { error: delivery.error }).catch(() => {});
    throw error;
  }
}

/** HTTPS remotes get the token as a header via env-based git config (never argv); SSH remotes use the agent. */
function pushAuth(remoteUrl: string, token: string | undefined) {
  const passEnv = ['SSH_AUTH_SOCK', 'GIT_SSH_COMMAND', 'GIT_ASKPASS', 'SSH_ASKPASS'];
  const https = /^https:\/\/([^/@]+@)?([^/]+)\//.exec(remoteUrl);
  if (!token || !https) return { passEnv, timeoutMs: 300_000 };
  const basic = Buffer.from(`x-access-token:${token}`).toString('base64');
  return { passEnv, timeoutMs: 300_000, env: { GIT_CONFIG_COUNT: '1', GIT_CONFIG_KEY_0: `http.https://${https[2]}/.extraheader`, GIT_CONFIG_VALUE_0: `AUTHORIZATION: basic ${basic}`, GIT_TERMINAL_PROMPT: '0' } };
}

interface PullRequest { number: number; html_url: string; }
async function openOrUpdatePullRequest(gh: GitHub, repository: string, state: ProjectState, backlog: Backlog, cfg: Config['delivery']['pullRequest']): Promise<PullRequest> {
  const [owner] = repository.split('/');
  const title = `${state.document.name.replace(/\.[^.]+$/, '')}: ${backlog.tasks.length} tasks (${state.id})`;
  const body = pullRequestBody(state, backlog);
  const existing = await gh.call<PullRequest[]>('GET', `/repos/${repository}/pulls?state=open&head=${encodeURIComponent(`${owner}:${state.branch}`)}`);
  if (existing[0]) return await gh.call<PullRequest>('PATCH', `/repos/${repository}/pulls/${existing[0].number}`, { title, body });
  const base = cfg.base ?? (await gh.call<{ default_branch: string }>('GET', `/repos/${repository}`)).default_branch;
  return await gh.call<PullRequest>('POST', `/repos/${repository}/pulls`, { title, body, head: state.branch, base, draft: cfg.draft });
}

/** For callers that only have the project directory (UI/CLI): the PR body as markdown. */
export async function readPullRequestBody(dir: string): Promise<string> {
  const { state, backlog } = await readProject(dir);
  return backlog ? pullRequestBody(state, backlog) : await readFile(join(dir, 'report.md'), 'utf8');
}
